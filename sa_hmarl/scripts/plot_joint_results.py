"""Plot final SA-HMARL joint-training result figures.

This script intentionally uses the finalized numbers reported in README plus
the training-curve CSV generated by train_joint_multitopo_alternating.py.

Run from project root:
    PYTHONPATH=/mnt/d/project/DNN_Agent/sa_hmarl \
    /mnt/d/project/DNN_Agent/.venv/bin/python sa_hmarl/scripts/plot_joint_results.py
"""
from __future__ import annotations

import csv
import os
from pathlib import Path

os.environ.setdefault("MPLCONFIGDIR", "/tmp/matplotlib")

import matplotlib.pyplot as plt
import numpy as np


PROJECT_ROOT = Path(__file__).resolve().parents[2]
SA_ROOT = PROJECT_ROOT / "sa_hmarl"
EXP_DIR = SA_ROOT / "experiments"
FIG_DIR = EXP_DIR / "figures"
CURVE_CSV = EXP_DIR / "joint_multitopo_training_curve.csv"


TOPOLOGIES = ["net1", "net2", "net3"]

MAIN_RESULTS = {
    "Joint-Finetuned C+R": [0.1, 0.7, 5.0],
    "Separate C+R": [1.5, 2.1, 12.1],
    "Agent-C + KSP-BF": [1.8, 4.2, 14.7],
    "Compute-Greedy + KSP-BF": [2.0, 5.0, 18.7],
}

COMPONENT_RESULTS = {
    "Joint-Finetuned C+R": [0.1, 0.7, 5.0],
    "Separate C+R": [1.5, 2.1, 12.1],
    "Agent-C + KSP-BF": [1.8, 4.2, 14.7],
    "Compute-Greedy + Agent-R-DQN": [0.0, 0.9, 5.7],
    "Compute-Greedy + KSP-BF": [2.0, 5.0, 18.7],
}

TEAM_ABLATION = {
    "Joint team=0.02": [0.1, 0.7, 5.0],
    "Joint team=0.0": [0.2, 0.7, 5.6],
    "Separate C+R": [1.5, 2.1, 12.1],
    "Compute-Greedy + Agent-R-DQN": [0.0, 0.9, 5.7],
}

NET3_MODULATION = {
    "Joint-Finetuned C+R": {"16QAM": 80.4, "8QAM": 1.3, "QPSK": 17.5, "BPSK": 0.8},
    "Separate C+R": {"16QAM": 0.1, "8QAM": 5.8, "QPSK": 37.3, "BPSK": 56.9},
    "Agent-C + KSP-BF": {"16QAM": 0.3, "8QAM": 0.0, "QPSK": 3.0, "BPSK": 96.7},
    "Compute-Greedy + KSP-BF": {"16QAM": 0.7, "8QAM": 2.0, "QPSK": 6.4, "BPSK": 91.0},
}


COLORS = {
    "joint": "#2364aa",
    "separate": "#73bfb8",
    "agent_c": "#f6ae2d",
    "agent_r": "#7d5fff",
    "greedy": "#f26419",
    "spectrum": "#8a817c",
    "grid": "#d9dee7",
    "text": "#1f2933",
}


def _style() -> None:
    plt.rcParams.update(
        {
            "figure.dpi": 160,
            "savefig.dpi": 240,
            "font.size": 10,
            "axes.titlesize": 13,
            "axes.labelsize": 10,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.color": COLORS["grid"],
            "grid.linewidth": 0.8,
            "grid.alpha": 0.65,
            "legend.frameon": False,
        }
    )


def _save(fig: plt.Figure, name: str) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    for suffix in (".png", ".pdf"):
        fig.savefig(FIG_DIR / f"{name}{suffix}", bbox_inches="tight")
    plt.close(fig)


def _method_color(method: str) -> str:
    if method.startswith("Joint"):
        return COLORS["joint"]
    if method.startswith("Separate"):
        return COLORS["separate"]
    if method.startswith("Agent-C"):
        return COLORS["agent_c"]
    if "Agent-R" in method:
        return COLORS["agent_r"]
    return COLORS["greedy"]


def plot_main_blocking() -> None:
    methods = list(MAIN_RESULTS)
    x = np.arange(len(TOPOLOGIES))
    width = 0.18
    fig, ax = plt.subplots(figsize=(9.4, 4.8))

    offsets = np.linspace(-1.5 * width, 1.5 * width, len(methods))
    for method, offset in zip(methods, offsets):
        values = MAIN_RESULTS[method]
        bars = ax.bar(x + offset, values, width, label=method, color=_method_color(method))
        ax.bar_label(bars, labels=[f"{v:.1f}%" for v in values], padding=2, fontsize=8)

    ax.set_title("Blocking Rate by Topology")
    ax.set_ylabel("Blocking rate (%)")
    ax.set_xticks(x)
    ax.set_xticklabels(TOPOLOGIES)
    ax.set_ylim(0, 21)
    ax.legend(ncols=2, loc="upper left")
    _save(fig, "main_blocking_by_topology")


def plot_component_contribution() -> None:
    methods = list(COMPONENT_RESULTS)
    avg = [np.mean(COMPONENT_RESULTS[m]) for m in methods]
    order = np.argsort(avg)
    sorted_methods = [methods[i] for i in order]
    sorted_avg = [avg[i] for i in order]

    fig, ax = plt.subplots(figsize=(9.5, 4.9))
    y = np.arange(len(sorted_methods))
    bars = ax.barh(y, sorted_avg, color=[_method_color(m) for m in sorted_methods])
    ax.bar_label(bars, labels=[f"{v:.1f}%" for v in sorted_avg], padding=4)
    ax.set_yticks(y)
    ax.set_yticklabels(sorted_methods)
    ax.set_xlabel("Average blocking across net1/net2/net3 (%)")
    ax.set_title("Component Contribution: Lower Is Better")
    ax.set_xlim(0, max(sorted_avg) * 1.2)
    _save(fig, "component_contribution_avg_blocking")


def plot_team_ablation() -> None:
    methods = list(TEAM_ABLATION)
    avg = [np.mean(TEAM_ABLATION[m]) for m in methods]
    colors = [COLORS["joint"], "#4f86c6", COLORS["separate"], COLORS["agent_r"]]

    fig, ax = plt.subplots(figsize=(8.5, 4.6))
    x = np.arange(len(methods))
    bars = ax.bar(x, avg, color=colors)
    ax.bar_label(bars, labels=[f"{v:.1f}%" for v in avg], padding=3)
    ax.set_xticks(x)
    ax.set_xticklabels(methods, rotation=18, ha="right")
    ax.set_ylabel("Average blocking (%)")
    ax.set_title("Team Reward Ablation")
    ax.set_ylim(0, max(avg) * 1.35)
    _save(fig, "team_reward_ablation")


def plot_net3_modulation() -> None:
    methods = list(NET3_MODULATION)
    mods = ["16QAM", "8QAM", "QPSK", "BPSK"]
    mod_colors = {
        "16QAM": "#2364aa",
        "8QAM": "#3da5d9",
        "QPSK": "#73bfb8",
        "BPSK": "#f6ae2d",
    }

    fig, ax = plt.subplots(figsize=(9.5, 4.8))
    x = np.arange(len(methods))
    bottom = np.zeros(len(methods))
    for mod in mods:
        values = [NET3_MODULATION[m][mod] for m in methods]
        ax.bar(x, values, bottom=bottom, label=mod, color=mod_colors[mod])
        bottom += np.array(values)

    ax.set_title("net3 Modulation Distribution")
    ax.set_ylabel("Share of successful allocations (%)")
    ax.set_xticks(x)
    ax.set_xticklabels(methods, rotation=18, ha="right")
    ax.set_ylim(0, 100)
    ax.legend(ncols=4, loc="upper center", bbox_to_anchor=(0.5, 1.13))
    _save(fig, "net3_modulation_distribution")


def _read_curve() -> dict[str, list[float]]:
    with CURVE_CSV.open(newline="") as f:
        rows = list(csv.DictReader(f))
    data: dict[str, list[float]] = {k: [] for k in rows[0]}
    for row in rows:
        for key, value in row.items():
            data[key].append(float(value))
    return data


def plot_training_curve() -> None:
    data = _read_curve()
    episodes = np.array(data["episode"])
    avg_blocking = np.array(data["avg_blocking"]) * 100
    net3_blocking = np.array(data["net3_blocking"]) * 100
    mod_16qam = np.array(data["mod_16qam"]) * 100

    fig, ax1 = plt.subplots(figsize=(9.5, 4.8))
    ax1.plot(episodes, avg_blocking, color=COLORS["joint"], marker="o", label="Avg blocking")
    ax1.plot(episodes, net3_blocking, color=COLORS["greedy"], marker="s", alpha=0.85, label="net3 blocking")
    ax1.set_xlabel("Training episode")
    ax1.set_ylabel("Blocking rate (%)")
    ax1.set_ylim(0, max(net3_blocking) * 1.18)

    ax2 = ax1.twinx()
    ax2.plot(episodes, mod_16qam, color="#2a9d8f", marker="^", linestyle="--", label="16QAM share")
    ax2.set_ylabel("16QAM share (%)")
    ax2.set_ylim(0, 100)
    ax2.grid(False)

    best_idx = int(np.argmin(avg_blocking))
    best_ep = int(episodes[best_idx])
    ax1.axvline(best_ep, color="#111827", linestyle=":", linewidth=1.2)
    ax1.annotate(
        f"best ep {best_ep}\n{avg_blocking[best_idx]:.1f}% avg blk",
        xy=(best_ep, avg_blocking[best_idx]),
        xytext=(best_ep + 110, avg_blocking[best_idx] + 2.4),
        arrowprops={"arrowstyle": "->", "color": "#111827", "lw": 1},
        fontsize=9,
    )

    lines1, labels1 = ax1.get_legend_handles_labels()
    lines2, labels2 = ax2.get_legend_handles_labels()
    ax1.legend(lines1 + lines2, labels1 + labels2, loc="upper right")
    ax1.set_title("Joint Fine-Tuning Curve")
    _save(fig, "joint_training_curve")


def plot_all() -> None:
    _style()
    plot_main_blocking()
    plot_component_contribution()
    plot_team_ablation()
    plot_net3_modulation()
    plot_training_curve()
    print(f"Saved figures to {FIG_DIR}")


if __name__ == "__main__":
    plot_all()
